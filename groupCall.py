"""
groupCall.py — batch orchestrator for generateShortRead.py.

This is the driver most experiments were launched through. It reads a list
of plasmid pairs (in various file formats produced at different stages of
the project) and fans out calls to `generateShortRead.py` in parallel
subprocess batches, one call per pair, so each pair's fragment-ordering
distance distribution gets computed and appended to an allDistances_*.txt
file.

The different functions below are essentially one experiment each — they
existed to point the same batching logic at a different input file or
plasmid subset (real sequencing data, synthetic rearrangements, binned
fragments, filtered subsets, etc.) as the analysis evolved. `func` (see
__main__) selects which one runs.

Data sources referenced by these functions:
  fastas/            Original full-length plasmid assemblies from the pling
                      GitHub repo. Artificially fragmented for testing since
                      short-read assembly does not yield full-length plasmids.
  syntethic/          Synthetic plasmid database generated by this project
                      (see syntethic.py) by applying random rearrangement
                      events to the fastas/ plasmids — used to get distance
                      pairs with a known ground-truth rearrangement distance.
  plasmid_references/ Reference (full-length) plasmid sequences corresponding
                      to a real short-read dataset from another paper.
  binned_fragments/   Contigs from that real short-read dataset, assigned
                      ("binned") to whichever plasmid_references/ sequence
                      they best align to (see bin_fragments.py) — this is
                      the real short-read test case, as opposed to the
                      artificially fragmented fastas/ / syntethic/ data.

CLI: python groupCall.py <func> <size> <implementation:true|false>
  func            selects which experiment function to run (0-8, see __main__)
  size            number of fragments to split each plasmid into
  implementation  "true" to use break_distance.my_implementation,
                  "false" to use pling
"""
