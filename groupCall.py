def run_syntethic(size):
	"""func=3. For every synthetic plasmid under syntethic/regenerated/,
	runs generateShortRead.py against its original counterpart in
	./fastas/, always with implementation=True (break_distance.my_implementation),
	fragmenting into `size` pieces."""
	plasmid_files = subprocess.check_output("ls -1 syntethic/regenerated",shell=True,text=True)
	files = plasmid_files.split("\n")[:-1]
	
	i=0
	for f in files:
		og = f.split(".1")[0]
		subprocess.call(f"python ./generateShortRead.py /fastas/{og}.1.fna /syntethic/regenerated/{f} {i} {1} {size} True",shell=True)
		i+=1

def generate_syntethic():
	"""func=2 (the definition actually in effect, see note on the earlier
	duplicate above). Picks 30 random plasmids referenced in
	./old_results/allDistances_v2_1.txt and generates a synthetic rearranged
	variant of each via syntethic.run(), at a random fragment count between
	1 and 19."""
	plasmid_pairs = set()
	with open("./old_results/allDistances_v2_1.txt") as f:
		for line in f:
			if "/" in line:
				plasmid_pairs.add("/fastas/"+line.split("/")[2].strip())
				plasmid_pairs.add("/fastas/"+line.split("/")[4].strip())
	k=30
	plasmid = rm.sample(sorted(plasmid_pairs),k)
	for i in range(k):
		nr_of_fragments = rm.randrange(1,20)
		run(plasmid[i],nr_of_fragments)

