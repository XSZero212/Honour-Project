def sample_random_plasmids():
	"""func=0. Reads plasmid pairs from uniqueDistancesv2.txt and processes
	them in an infinite loop, 10 pairs (`parralel`) per batch."""
	pair_plasmids = []
	with open("uniqueDistancesv2.txt") as f:
		for x in f:
			s = x.strip()
			pair_plasmids.append((s.split()[0][1:],s.split()[1][1:]))

	i = 0
	k = 0
	size = 6
	parallel = 10
	while True:
		plasmids_pairs = rm.sample(pair_plasmids,10)
		commands = [f"python ./generateShortRead.py {j[0]} {j[1]} {k} {index} {size} {implementation}" for index,j in enumerate(plasmids_pairs[i:i+parallel])]
		procs = [subprocess.Popen(j,shell=True) for j in commands]
		for p in procs:
			p.wait()
		print(f"The batch finished {i}")
		i+=parallel
		k+=1

def sample_continous(implementation):
	"""func=4. Reads plasmid pairs from input_syntethic.txt (see
	create_input()) and processes them in batches of 10 in parallel,
	fragmenting each plasmid into 6 pieces. Cleans up the intermediate
	py_out/ input/fasta files after each batch unless implementation=True
	(the my_implementation path needs them to persist for inspection)."""
	pair_plasmids = []
	with open("input_syntethic.txt") as f:
		for x in f:
			s = x.strip()
			pair_plasmids.append((s.split()[0][1:],s.split()[1][1:]))

	i=0
	k=0
	parralel = 10
	while i<len(pair_plasmids):
		commands = [f"python ./generateShortRead.py {j[0]} {j[1]} {k} {index} {6} {implementation}" for index,j in enumerate(pair_plasmids[i:i+parralel])]
		procs = [subprocess.Popen(j,shell=True) for j in commands]
		for p in procs:
			p.wait()
		if not implementation:
			for index,_ in enumerate(pair_plasmids[i:i+parralel]):
				subprocess.call(f"rm -r ./py_out/input{k}_{index}.txt", shell=True)
				subprocess.call(f"rm -r ./py_out/try{k}_{index}.fasta", shell=True)
		print(f"The batch finished {i}")
		i+=parralel
		k+=1

